import { createHash } from 'node:crypto';
import type { RepoContext, RenderedFile, StageOutput, PromptStage, Target } from './types.js';

const marker = (context: RepoContext) => createHash('sha256').update(JSON.stringify(context)).digest('hex').slice(0, 12);

const header = (context: RepoContext) => `<!-- Generated by ai-meta-factory; context ${marker(context)}. Do not edit manually. -->
`;

const summary = (context: RepoContext) => `# ${context.repository.name} — Project Context

- Languages: ${context.repository.languages.join(', ') || 'unknown'}
- Runtime: ${context.stack.runtime ?? 'unknown'}
- Frameworks: ${context.stack.frameworks.join(', ') || 'none'}
- Package Manager: ${context.stack.packageManager ?? 'unknown'}

## Entry Points
${context.structure.entryPoints.map((ep) => `- ${ep}`).join('\n') || 'None detected'}

## Key Directories
${context.structure.directories.map((dir) => `- ${dir}/`).join('\n') || 'None'}

## Build Commands
- Build: \`${context.commands.build ?? 'N/A'}\`
- Test: \`${context.commands.test ?? 'N/A'}\`
- Dev: \`${context.commands.dev ?? 'N/A'}\`

## Constraints
${context.constraints.map((c) => `- ${c}`).join('\n')}
`;

