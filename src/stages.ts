// ============================================================================
// PIPELINE ORCHESTRATION
// ============================================================================
export function stagePipeline(context: RepoContext, target: Exclude<Target, 'all'>, stages?: PromptStage[]): StageOutput[] {
  const stageMap: Record<Exclude<PromptStage, 'all'>, (ctx: RepoContext, tgt: Exclude<Target, 'all'>) => RenderedFile[]> = {
    'scanner': (ctx) => stageScanner(ctx),
    'context-generator': (ctx, tgt) => stageContextGenerator(ctx, tgt),
    'architecture': (ctx, tgt) => stageArchitecture(ctx, tgt),
    'standards': (ctx, tgt) => stageStandards(ctx, tgt),
    'tests': (ctx, tgt) => stageTests(ctx, tgt),
    'drift-check': (ctx) => stageDriftCheck(ctx),
    'claudemd': (ctx, tgt) => stageClaudemd(ctx, tgt)
  };

  const execution: Exclude<PromptStage, 'all'>[] = stages === undefined || stages.includes('all')
    ? ['scanner', 'context-generator', 'architecture', 'standards', 'tests', 'drift-check', 'claudemd']
    : stages.filter((s) => s !== 'all') as Exclude<PromptStage, 'all'>[];

  const results: StageOutput[] = [];
  for (const stage of execution) {
    const generator = stageMap[stage];
    if (!generator) {
      results.push({
        stage,
        target,
        files: [],
        timestamp: new Date().toISOString(),
        status: 'skipped'
      });
      continue;
    }
    const files = generator(context, target);
    results.push({
      stage,
      target,
      files,
      timestamp: new Date().toISOString(),
      status: 'success'
    });
  }
  return results;
}
